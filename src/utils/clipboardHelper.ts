/**
 * Robust copy-to-clipboard function that works in restricted iframes
 * using modern navigator.clipboard with a reliable textarea fallback.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  if (!text) return false;

  // Method 1: Try modern Clipboard API
  if (navigator?.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fall through to fallback
    }
  }

  // Method 2: Document execCommand fallback for iframes
  try {
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed';
    textArea.style.left = '-999999px';
    textArea.style.top = '-999999px';
    textArea.setAttribute('readonly', '');
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    if (successful) return true;
  } catch {
    // Both failed
  }

  return false;
}

/**
 * Triggers a download of formatted Google Doc content as a .doc file
 * that can be opened or dragged directly into Google Docs.
 */
export function downloadGoogleDocFile(title: string, formattedText: string, date: string) {
  const htmlContent = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>${title} - ${date}</title>
<style>
body { font-family: Arial, sans-serif; line-height: 1.6; color: #111; max-width: 800px; margin: 40px auto; padding: 20px; }
h1 { color: #1a73e8; font-size: 24px; border-bottom: 2px solid #1a73e8; padding-bottom: 8px; }
h2 { color: #202124; font-size: 18px; margin-top: 24px; border-bottom: 1px solid #ddd; padding-bottom: 4px; }
p { font-size: 14px; margin-bottom: 12px; }
ul, ol { margin-left: 20px; font-size: 14px; }
li { margin-bottom: 6px; }
blockquote { border-left: 4px solid #1a73e8; padding-left: 12px; color: #555; font-style: italic; margin: 12px 0; }
.meta { color: #70757a; font-size: 12px; margin-bottom: 20px; }
</style>
</head>
<body>
<h1>${title}</h1>
<div class="meta">Date: ${date} • Generated by ChatGPT Product Pulse HITL System</div>
<pre style="white-space: pre-wrap; font-family: inherit;">${formattedText}</pre>
</body>
</html>`;

  const blob = new Blob([htmlContent], { type: 'application/msword;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `ChatGPT_Product_Pulse_${date.replace(/[^a-zA-Z0-9]/g, '_')}.doc`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
